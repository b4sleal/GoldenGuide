"""Google Gemini LLM adapter: streamed answers and JSON-schema structured output."""
import structlog
from google import genai
from google.genai import types
from pydantic import BaseModel

from backend.domain.entities.llm import LLMRequest, MessageRole
from backend.domain.settings.llm import GeminiLLMSettings

logger = structlog.get_logger()

# Gemini names the assistant turn "model".
ROLES = {MessageRole.USER: "user", MessageRole.ASSISTANT: "model"}


def to_contents(request: LLMRequest) -> list[types.Content]:
    return [
        types.Content(role=ROLES[message.role], parts=[types.Part.from_text(text=message.content)])
        for message in request.messages
    ]


class GeminiLLM:
    def __init__(self, settings: GeminiLLMSettings):
        # The key comes from configuration (${secrets:...}), never from source code.
        self.client = genai.Client(api_key=settings.api_key.get_secret_value())
        self.model_name = settings.model_name

    async def generate_stream(self, request: LLMRequest):
        """Yields text chunks as they are generated by the LLM."""
        response = await self.client.aio.models.generate_content_stream(
            model=self.model_name,
            contents=to_contents(request),
            config=types.GenerateContentConfig(system_instruction=request.system),
        )

        async for chunk in response:
            if chunk.text:
                yield chunk.text

    async def generate_structured[T: BaseModel](
            self,
            request: LLMRequest,
            response_model: type[T],
    ) -> T:
        """`response_model` parsed from JSON the model must produce for its schema (temperature 0)."""
        response = await self.client.aio.models.generate_content(
            model=self.model_name,
            contents=to_contents(request),
            config=types.GenerateContentConfig(
                system_instruction=request.system,
                response_mime_type="application/json",
                response_json_schema=response_model.model_json_schema(),
                temperature=0,
            ),
        )

        if not response.text:
            raise ValueError(
                "Gemini returned an empty structured response"
            )

        return response_model.model_validate_json(response.text)
